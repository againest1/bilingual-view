import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const patch = JSON.parse(await readFile(join(root, 'patches/micromark-util-edit-map.json'), 'utf8'));
const packageRoot = dirname(require.resolve(patch.package));
const manifest = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'));
if (manifest.version !== patch.version) throw new Error('Review the Markdown patch before changing its dependency version.');
const digest = source => createHash('sha256').update(source).digest('hex');
const patched = new Map();
for (const [file, hashes] of Object.entries(patch.files)) {
  const path = join(packageRoot, file), source = await readFile(path, 'utf8');
  if (digest(source) !== hashes.before) throw new Error(`Unexpected dependency contents: ${file}. Review the Markdown patch.`);
  // The two-line runtime change from PR #249. Dependencies on disk stay pristine.
  const contents = source.replace(/^    vecs\.push\(events\.slice\(\)\);?\n    events\.length = 0;?\n/m, '');
  if (digest(contents) !== hashes.after) throw new Error(`The Markdown patch did not apply exactly: ${file}.`);
  patched.set(path, contents);
}

const result = await build({
  absWorkingDir: root,
  entryPoints: ['scripts/markdown-entry.mjs'],
  outfile: 'plugins/bilingual-view/hooks/vendor/markdown.js',
  bundle: true, format: 'esm', platform: 'node', target: 'es2022',
  write: false, metafile: true, legalComments: 'inline',
  banner: { js: '// Generated by npm run build. micromark 4.0.3 + GFM 3.0.0 + PR #249.\n// Third-party licenses: ../../THIRD_PARTY_LICENSES.txt. Edit scripts/markdown-entry.mjs instead.' },
  plugins: [{ name: 'fixed-edit-map', setup(builder) {
    builder.onLoad({ filter: /micromark-util-edit-map[/\\](?:dev[/\\])?index\.js$/ }, async args => {
      const contents = patched.get(args.path);
      if (contents === undefined) throw new Error('Unexpected copy of micromark-util-edit-map in the dependency tree.');
      return { contents, loader: 'js', resolveDir: dirname(args.path) };
    });
  } }],
});
if (Object.values(result.metafile.outputs).some(output => output.imports.length)) {
  throw new Error('The Markdown bundle must have no external imports.');
}

const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const path = resolve(root, input), marker = sep + 'node_modules' + sep;
  const at = path.lastIndexOf(marker);
  if (at < 0) continue;
  const parts = path.slice(at + marker.length).split(sep);
  const directory = path.slice(0, at + marker.length) + parts.slice(0, parts[0].startsWith('@') ? 2 : 1).join(sep);
  const metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  const files = await readdir(directory);
  const licenseFile = files.find(file => /^licen[cs]e(?:\.md|\.txt)?$/i.test(file));
  if (!licenseFile) throw new Error(`Missing license for bundled dependency ${metadata.name}.`);
  packages.set(metadata.name + '@' + metadata.version, await readFile(join(directory, licenseFile), 'utf8'));
}
const licenses = 'Third-party code bundled in hooks/vendor/markdown.js\n'
  + `micromark-util-edit-map ${patch.version} includes the runtime change from ${patch.upstream}.\n\n`
  + [...packages].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
    .map(([name, license]) => name + '\n' + '='.repeat(name.length) + '\n' + license.trim() + '\n').join('\n');
const outputs = [...result.outputFiles.map(file => [file.path, file.text]),
  [join(root, 'plugins/bilingual-view/THIRD_PARTY_LICENSES.txt'), licenses]];
for (const [path, contents] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== contents) throw new Error(`Generated file is out of date: ${relative(root, path)}. Run npm run build.`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, contents);
  }
}
console.log(process.argv.includes('--check') ? 'Markdown bundle and licenses are up to date.' : 'Built Markdown bundle and licenses.');
